const born = (age = 24) => createNewCharacter({ seed: `balance-regression-${age}`, startAge: age });
const thumb = born(20);
thumb.job = 'Syndicate';
thumb.finger = 'Thumb';
thumb.fingerRank = 0;
thumb.merit = 200;
thumb.stats.rep = 100;
assert.equal(getNextFingerPromotion(thumb).isEligible, false);
thumb.age = 22;
assert.equal(getNextFingerPromotion(thumb).isEligible, true);
thumb.fingerRank = 1;
thumb.lastFingerPromotionAge = 22;
thumb.age = 27;
assert.equal(getNextFingerPromotion(thumb).isEligible, false);
thumb.age = 28;
assert.equal(getNextFingerPromotion(thumb).isEligible, true);
thumb.fingerRank = 2;
thumb.lastFingerPromotionAge = 28;
thumb.age = 34;
assert.equal(getNextFingerPromotion(thumb).isEligible, false);
thumb.age = 35;
assert.equal(getNextFingerPromotion(thumb).isEligible, true);

const etiquette = FACTION_EVENTS.find((event) => event.id === 'syn_thumb_tongue_etiquette');
const soldato = born(22);
soldato.job = 'Syndicate';
soldato.finger = 'Thumb';
soldato.fingerRank = 0;
soldato.pendingEvent = etiquette;
const afterEtiquette = resolveEventChoice(soldato, 0, () => 0.5);
assert.equal(afterEtiquette.fingerRank, 0);
assert.equal(isEventEligible(etiquette, { ...soldato, fingerRank: 1 }), false);
soldato.pendingEvent = etiquette;
const expelled = resolveEventChoice(soldato, 1, () => 0.5);
assert.equal(expelled.job, 'Outcast');
assert.equal(expelled.finger, null);
assert.ok(expelled.weaver.pendingThreads.some((thread) => thread.eventId === 'csq_thumb_etiquette_hunt'));

const fixer = born(29);
fixer.job = 'Fixer';
fixer.fixerGrade = 1;
fixer.merit = 350;
fixer.stats.rep = 100;
assert.equal(checkColorFixerReadiness(fixer).ready, false);
fixer.age = 30;
assert.equal(checkColorFixerReadiness(fixer).ready, true);
fixer.stats.health = 31;
fixer.stats.sanity = 27;
fixer.pendingContract = generateFixerContract(fixer, () => 0.5);
const declined = resolveFixerContract(fixer, 'decline', () => 0.5);
