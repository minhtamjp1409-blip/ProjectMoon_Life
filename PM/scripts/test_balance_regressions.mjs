import assert from 'node:assert/strict';
import { createNewCharacter, generateFixerContract, resolveFixerContract, resolveEventChoice } from '../src/engine/gameEngine.js';
import { getNextFingerPromotion, checkColorFixerReadiness } from '../src/engine/careerPipeline.js';
import { healAmount, calmAmount, driftOf } from '../src/engine/economyModel.js';
import { addScar } from '../src/engine/scarModel.js';
import { isEventEligible } from '../src/engine/weaverAI.js';
import { FACTION_EVENTS } from '../src/data/eventsFactions.js';
import { DERIVATIVE_LORE_EVENTS } from '../src/data/eventsDerivativeLore.js';
import { LIFE_MINORS, endYear } from '../src/engine/yearPlanner.js';
import { matchesEventContext } from '../src/engine/eventConditions.js';

const born = (age = 24) => createNewCharacter({ seed: `balance-regression-${age}`, startAge: age });
const thumb = born(20);
thumb.job = 'Syndicate';
thumb.finger = 'Thumb';
thumb.fingerRank = 0;
thumb.merit = 200;
thumb.stats.rep = 100;
assert.equal(getNextFingerPromotion(thumb).isEligible, false);
thumb.age = 22;
assert.equal(getNextFingerPromotion(thumb).isEligible, true);
thumb.fingerRank = 1;
thumb.lastFingerPromotionAge = 22;
thumb.age = 27;
assert.equal(getNextFingerPromotion(thumb).isEligible, false);
thumb.age = 28;
assert.equal(getNextFingerPromotion(thumb).isEligible, true);
thumb.fingerRank = 2;
thumb.lastFingerPromotionAge = 28;
thumb.age = 34;
assert.equal(getNextFingerPromotion(thumb).isEligible, false);
thumb.age = 35;
assert.equal(getNextFingerPromotion(thumb).isEligible, true);

const etiquette = FACTION_EVENTS.find((event) => event.id === 'syn_thumb_tongue_etiquette');
const soldato = born(22);
soldato.job = 'Syndicate';
soldato.finger = 'Thumb';
soldato.fingerRank = 0;
soldato.pendingEvent = etiquette;
const afterEtiquette = resolveEventChoice(soldato, 0, () => 0.5);
assert.equal(afterEtiquette.fingerRank, 0);
assert.equal(isEventEligible(etiquette, { ...soldato, fingerRank: 1 }), false);
soldato.pendingEvent = etiquette;
const expelled = resolveEventChoice(soldato, 1, () => 0.5);
assert.equal(expelled.job, 'Outcast');
assert.equal(expelled.finger, null);
assert.ok(expelled.weaver.pendingThreads.some((thread) => thread.eventId === 'csq_thumb_etiquette_hunt'));

const fixer = born(29);
fixer.job = 'Fixer';
fixer.fixerGrade = 1;
fixer.merit = 350;
fixer.stats.rep = 100;
assert.equal(checkColorFixerReadiness(fixer).ready, false);
fixer.age = 30;
assert.equal(checkColorFixerReadiness(fixer).ready, true);
fixer.stats.health = 31;
fixer.stats.sanity = 27;
fixer.pendingContract = generateFixerContract(fixer, () => 0.5);
const declined = resolveFixerContract(fixer, 'decline', () => 0.5);
assert.equal(declined.stats.health, 31);
assert.equal(declined.stats.sanity, 27);
assert.equal(declined.merit, fixer.merit);

const wounded = born(25);
wounded.stats.health = 25;
wounded.stats.sanity = 25;
assert.ok(healAmount(wounded, 'natural') >= 3 && healAmount(wounded, 'natural') <= 5);
assert.ok(calmAmount(wounded, 'bond') >= 3 && calmAmount(wounded, 'bond') <= 5);
for (let i = 0; i < 8; i += 1) addScar(wounded, `Di chứng ${i}`);
assert.equal(wounded.scars.length, 4);

const blade = DERIVATIVE_LORE_EVENTS.find((event) => event.id === 'bl_claim_their_bones_oath');
const kurokumo = DERIVATIVE_LORE_EVENTS.find((event) => event.id === 'kurokumo_ink_slash_vendetta');
wounded.job = 'Fixer';
assert.equal(isEventEligible(blade, wounded), true);
wounded.flags.push('kurokumo_tattooed');
assert.equal(isEventEligible(blade, wounded), false);
wounded.flags.pop();
wounded.flags.push('blade_lineage_sworn');
assert.equal(isEventEligible(kurokumo, wounded), false);

const initiate = born(24);
initiate.job = 'Fixer';
initiate.pendingEvent = blade;
const sworn = resolveEventChoice(initiate, 0, () => 0.5);
assert.ok(sworn.flags.includes('blade_lineage_sworn'));
assert.ok(sworn.weaver.pendingThreads.some((thread) => thread.eventId === 'csq_kurokumo_retribution'));
assert.equal(isEventEligible(kurokumo, sworn), false);

assert.equal(LIFE_MINORS.find((event) => event.id === 'm_syn_order').once, true);

const rich = born(30);
rich.job = 'Wing Employee';
rich.stats.health = 100;
rich.stats.sanity = 100;
rich.stats.wealth = 100;
rich.stats.network = 100;
rich.stats.rep = 100;
rich.resonance = 100;
assert.equal(matchesEventContext(LIFE_MINORS.find((event) => event.id === 'm_med_nest_infirmary'), rich), false);
const clinic = LIFE_MINORS.find((event) => event.id === 'm_med_backstreet_clinic');
const hamham = LIFE_MINORS.find((event) => event.id === 'm_wellness_hamham_lunch');
assert.equal(matchesEventContext(clinic, rich), false);
assert.equal(matchesEventContext(hamham, rich), false);
assert.ok(clinic.choices[0].fx.health <= 35);
assert.equal(LIFE_MINORS.find((event) => event.id === 'm_wellness_workshop_tuneup').choices[0].fx.health, undefined);
const richEnd = endYear(rich, () => 0.5);
for (const key of ['health', 'sanity', 'wealth', 'network', 'rep']) assert.ok(richEnd.stats[key] < 100, key);
assert.ok(richEnd.resonance < 100);
rich.flags.push('EGOAwakened');
assert.ok(driftOf(rich).resonance < 0);
rich.stats.health = 50;
rich.stats.sanity = 50;
assert.equal(matchesEventContext(clinic, rich), true);
assert.equal(matchesEventContext(hamham, rich), true);
rich.regionId = 'OUTSKIRTS';
assert.equal(matchesEventContext(hamham, rich), false);
const outskirtsChild = born(12);
outskirtsChild.regionId = 'OUTSKIRTS';
outskirtsChild.stats.health = 50;
assert.equal(matchesEventContext(LIFE_MINORS.find((event) => event.id === 'm_med_child_remedy'), outskirtsChild), false);

console.log('Balance regressions: rank gates, etiquette, Color age, decline, recovery, scars, rival clans, one-time order, resource upkeep and care context passed.');
