import assert from 'node:assert/strict';
import { createNewCharacter, generateFixerContract, resolveFixerContract, resolveEventChoice } from '../src/engine/gameEngine.js';
import { getNextFingerPromotion, checkColorFixerReadiness } from '../src/engine/careerPipeline.js';
import { healAmount, calmAmount, agingLoss, driftOf } from '../src/engine/economyModel.js';
import { addScar } from '../src/engine/scarModel.js';
import { isEventEligible } from '../src/engine/weaverAI.js';
import { FACTION_EVENTS } from '../src/data/eventsFactions.js';
